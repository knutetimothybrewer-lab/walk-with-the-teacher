#!/usr/bin/env python3
"""Writes apps-script/SeedData.gs (the Lessons and Criteria tabs) from data/lessons.json.
Safe to publish: contains lesson titles, objectives and criteria only, no items and no answer keys.
Run from pre-post-tickets/:  python3 -I tools/build_sheet_seed.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
lessons = json.loads((ROOT / "data" / "lessons.json").read_text())

REVIEW_OBJECTIVE = "Show what you remember from the earlier lessons in this unit."
L, C = [], []
for l in lessons:
    title = l["title"].replace(" (no lesson plan file yet)", "")
    obj = REVIEW_OBJECTIVE if l["ticket_type"] == "unit_review" else l["objective"]
    L.append([l["sequence"], l["lesson_id"], l["unit"], l["unit_title"], l["day"], title, obj, l["ticket_type"]])
    # review days are projects: their items carry criteria from the earlier lessons, so they get no criteria of their own
    for c in l["criteria"] if l["status"] == "ok" and l["ticket_type"] == "daily" else []:
        C.append([c["criterion_id"], l["lesson_id"], c["text"], "Y" if c.get("observed") else "N"])

body = ("/** SeedData.gs - GENERATED by tools/build_sheet_seed.py. Do not edit by hand; edit the lessons and re-run it. */\n"
        "var LESSONS_SEED = " + json.dumps(L, indent=1, ensure_ascii=False) + ";\n\n"
        "var CRITERIA_SEED = " + json.dumps(C, indent=1, ensure_ascii=False) + ";\n")
(ROOT / "apps-script" / "SeedData.gs").write_text(body)
print(f"{len(L)} lessons, {len(C)} criteria")
