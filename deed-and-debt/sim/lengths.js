#!/usr/bin/env node
/* Estimates real play time for every game length in GAME_CONTENT.GAME_LENGTHS, for
   (a) a 4-player group of humans sharing a device and (b) 1 human playing solo against 3 computer players.
   Writes sim/LENGTHS.md.  Usage: node sim/lengths.js [games per length = 150]
   Time model (seconds, Normal animation speed), same as sim/simulate.js for human turns:
   - human turn: 20s of decisions (reading cards and choosing are inside this) + 1.1s turn banner (group only)
   - computer turn: no decision time; the game's own pauses (about 0.65s per computer step, 3 steps a turn)
     plus 4.5s for each card it draws (cards drawn by computers close themselves)
   - animation: 0.9s per roll, 0.15s per space hopped, 0.65s per rent payment, 1.1s per deed flip, 0.25s per building
   - auctions: 10s with humans bidding; 2s when only computers can bid
   - per Year: 1.9s banner + 15s event card + 15s Annual Report
   - per ballot: 30s to read + 4s per human vote + 5s tally
   Career picks (about 2.5 min for a group, 40s solo) are setup time and not counted. */
const fs = require('fs'), path = require('path');
const { Engine: E, C } = require('./load-engine')();
const N = +process.argv[2] || 150;
const T = { humanTurn: 20, turnBanner: 1.1, rerollDecision: 6, cpuStep: 0.65, cpuStepsPerTurn: 3, cpuCard: 4.5, perRoll: 0.9, perHop: 0.15, payFly: 0.65, deedFlip: 1.1, cardFlip: 0.6, build: 0.25,
  auctionHuman: 10, auctionCpu: 2, yearBanner: 1.9, eventCard: 15, annualReport: 15, ballotIntro: 30, ballotVote: 4, ballotTally: 5 };

function timeGame(seed, years, players, humans) {
  const strats = E.STRATEGIES.slice(0, players);
  const s = E.newGame({ seed, groupName: 'len', players: strats.map((st, i) => ({ name: 'P' + i, cpu: true, strategy: st })), settings: { years, quickChecks: false } });
  const isHuman = (pid) => pid < humans;
  let sec = 0, turnPid = null, rollsThisTurn = 0;
  while (s.flow.stage !== 'results') {
    const r = E.stepMut(s, { type: 'cpu' });
    if (r.error) throw new Error(r.error);
    for (const f of r.fx) {
      switch (f.t) {
        case 'turnStart': turnPid = f.pid; rollsThisTurn = 0; sec += isHuman(f.pid) ? T.humanTurn + (humans > 1 ? T.turnBanner : 0) : T.cpuStep * T.cpuStepsPerTurn; break;
        case 'dice': sec += T.perRoll; if (++rollsThisTurn > 1) sec += isHuman(turnPid) ? T.rerollDecision : T.cpuStep; break;
        case 'move': sec += f.path.length * T.perHop; break;
        case 'pay': sec += T.payFly; break;
        case 'buy': if (!f.trade) sec += T.deedFlip; break;
        case 'build': sec += T.build; break;
        case 'card': case 'cardShow': case 'taxday': sec += isHuman(f.pid) ? T.cardFlip : T.cpuCard; break;
        case 'auctionStart': sec += humans > 0 ? T.auctionHuman : T.auctionCpu; break;
        case 'yearStart': sec += T.yearBanner; break;
        case 'event': sec += T.eventCard; break;
        case 'annual': sec += T.annualReport; break;
        case 'ballotResult': sec += T.ballotIntro + T.ballotVote * humans + T.ballotTally; break;
      }
    }
  }
  return sec / 60;
}
const median = (a) => { const b = a.slice().sort((x, y) => x - y); return b[Math.floor(b.length / 2)]; };
const rows = [];
const lengths = C.GAME_LENGTHS.map(l => l.years);
for (const y of lengths) {
  const g = [], so = [];
  for (let seed = 1; seed <= N; seed++) { g.push(timeGame(seed, y, 4, 4)); so.push(timeGame(seed, y, 4, 1)); }
  const L = C.GAME_LENGTHS.find(l => l.years === y);
  rows.push({ y, name: L.name, group: median(g), solo: median(so), groupListed: L.groupMin, soloListed: L.soloMin, ballots: E.ballotYearsFor(y).length });
  console.log(L.name.padEnd(12), String(y).padStart(2), 'Years  group', median(g).toFixed(1), 'min  solo', median(so).toFixed(1), 'min  ballots', E.ballotYearsFor(y).join(','));
}
const md = '# DEED & DEBT: Game lengths\n\nGenerated by `node sim/lengths.js ' + N + '` (' + N + ' seeded games per length and mode). Median estimated minutes of play, at Normal animation speed, not counting career picks.\n\n' +
  '| Length | Years | Ballot votes | Group of 4 (est.) | Solo vs. 3 computers (est.) | Shown on setup screen (group / solo) |\n|---|---|---|---|---|---|\n' +
  rows.map(r => '| ' + r.name + ' | ' + r.y + ' | ' + r.ballots + ' | ' + r.group.toFixed(1) + ' min | ' + r.solo.toFixed(1) + ' min | ~' + r.groupListed + ' / ~' + r.soloListed + ' min |').join('\n') +
  '\n\nThe setup screen labels come from `GAME_LENGTHS` in `GAME_CONTENT`. After changing tuning numbers, rerun this script and update `groupMin` and `soloMin` to match.\n\n' +
  'Time model: ' + JSON.stringify(T) + ' (seconds).\n';
fs.writeFileSync(path.join(__dirname, 'LENGTHS.md'), md);
